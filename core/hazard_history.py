SIMULATION_DISCLAIMER_TEXT = (
    "DISCLAIMER: SIMULATED DATA ONLY — NOT REAL SENSOR READINGS. "
    "All telemetry snapshots, status evaluations, and statistical metrics in this report "
    "were generated by software simulation for testing, design demonstration, and educational purposes. "
    "They do NOT constitute certified workplace monitoring, industrial hygiene measurements, "
    "or statutory safety documentation (OSHA/NIOSH/ACGIH/ISO)."
)


@dataclass
class HazardEvent:
    """Represents a discrete environmental hazard state transition occurrence."""
    timestamp: str
    parameter_key: str
    display_name: str
    previous_status: HazardStatus
    new_status: HazardStatus
    value: float
    unit: str
    relevant_threshold: str
    reason: str
    recommended_action: str
    tick: int = 0
    iso_timestamp: str = ""

    def __post_init__(self):
        if not self.iso_timestamp:
            self.iso_timestamp = datetime.now().isoformat()

    @property
    def severity(self) -> HazardStatus:
        """Alias for backward compatibility with Phase 3."""
        return self.new_status

    @property
    def severity_label(self) -> str:
        return self.new_status.color_label

    @property
    def transition_label(self) -> str:
        return f"{self.previous_status.color_label} ➔ {self.new_status.color_label}"

    @property
    def is_warning(self) -> bool:
        return self.new_status == HazardStatus.WARNING

    @property
    def is_danger(self) -> bool:
        return self.new_status == HazardStatus.DANGER

    @property
    def is_recovery(self) -> bool:
        return self.new_status == HazardStatus.SAFE and self.previous_status != HazardStatus.SAFE

    def to_dict(self) -> Dict[str, Any]:
        """Provides display-ready dictionary representation for UI tables."""
        return {
            "Timestamp": self.timestamp,
            "Hazard Type": self.display_name,
            "State Transition": self.transition_label,
            "Observed Value": f"{self.value:.1f} {self.unit}",
            "Severity": f"{self.new_status.color_label} ({self.new_status.value})",
            "Relevant Threshold": self.relevant_threshold,
            "Diagnosis": self.reason,
            "Recommended Action": self.recommended_action,
            "Previous Status": self.previous_status.value,
            "New Status": self.new_status.value,
            "Tick": self.tick,
        }

    def to_export_dict(self) -> Dict[str, Any]:
        """Provides clean raw-value dictionary for JSON and CSV exports."""
        return {
            "timestamp": self.timestamp,
            "iso_timestamp": self.iso_timestamp,
            "parameter_key": self.parameter_key,
            "hazard_name": self.display_name,
            "previous_status": self.previous_status.value,
            "previous_status_color": self.previous_status.color_label,
            "new_status": self.new_status.value,
            "new_status_color": self.new_status.color_label,
            "observed_value": round(float(self.value), 2) if not (math.isnan(self.value) or math.isinf(self.value)) else 0.0,
            "unit": self.unit,
            "relevant_threshold": self.relevant_threshold,
            "diagnostic_reason": self.reason,
            "recommended_action": self.recommended_action,
            "tick": self.tick,
        }


class HazardHistoryTracker:
    """
    Manages in-memory rolling time-series telemetry, state-transition event logging,
    summary statistics, and CSV/JSON report exports for the active session.
    """

    def __init__(self, max_snapshots: int = 300, max_events: int = 300):
        self.max_snapshots = max_snapshots
        self.max_events = max_events
        self.snapshots: List[Dict[str, Any]] = []
        self.events: List[HazardEvent] = []

        # Maps param_key -> last known HazardStatus (initialized to None/SAFE)
        self._last_param_status: Dict[str, HazardStatus] = {}

        # Fingerprint of last recorded snapshot: (tick, mode, round(temp,1), ...)
        self._last_snapshot_fingerprint: Optional[Tuple[Any, ...]] = None

        # Session tracking
        self.session_start_time: datetime = datetime.now()
        self.session_start_str: str = self.session_start_time.strftime("%Y-%m-%d %H:%M:%S")

    @property
    def has_snapshots(self) -> bool:
        return len(self.snapshots) > 0

    @property
    def has_events(self) -> bool:
        return len(self.events) > 0

    @property
    def snapshot_count(self) -> int:
        return len(self.snapshots)

    @property
    def event_count(self) -> int:
        return len(self.events)

    def record_snapshot(
        self,
        readings: Dict[str, Any],
        tick: int = 0,
        timestamp: Optional[datetime] = None,
        site_assessment: Optional[SiteHazardAssessment] = None,
        mode: str = "manual",
        force: bool = False,
    ) -> bool:
        """
        Records a timestamped telemetry snapshot across all 5 parameters.
        Includes individual hazard statuses, overall site status, and simulation mode.
        Avoids recording duplicate records on identical static UI reruns.
        """
        now_dt = timestamp or datetime.now()
        now_str = now_dt.strftime("%Y-%m-%d %H:%M:%S")
        time_only_str = now_dt.strftime("%H:%M:%S")

        # Extract numerical values safely
        extracted_vals: Dict[str, float] = {}
        for key in ["temperature", "humidity", "dust", "noise", "gas"]:
            val = readings.get(key, 0.0)
            if isinstance(val, EnvironmentalReading):
                num_val = float(val.value)
            elif isinstance(val, (int, float)):
                num_val = float(val)
            elif isinstance(val, dict) and "value" in val:
                num_val = float(val["value"])
            else:
                num_val = 0.0

            if math.isnan(num_val) or math.isinf(num_val):
                num_val = 0.0
            extracted_vals[key] = round(num_val, 2)

        # Duplicate prevention fingerprint
        fingerprint = (
            tick,
            mode,
            extracted_vals["temperature"],
            extracted_vals["humidity"],
            extracted_vals["dust"],
            extracted_vals["noise"],
            extracted_vals["gas"],
        )

        if not force and self._last_snapshot_fingerprint == fingerprint:
            return False  # Skip duplicate identical record on static rerun

        self._last_snapshot_fingerprint = fingerprint

        # Extract statuses if site_assessment provided
        status_temp = "SAFE"
        status_hum = "SAFE"
        status_dust = "SAFE"
        status_noise = "SAFE"
        status_gas = "SAFE"
        overall_status_val = "SAFE"
        overall_status_color = "GREEN"

        if site_assessment is not None:
            overall_status_val = site_assessment.overall_status.value
            overall_status_color = site_assessment.overall_status.color_label
            ass_dict = site_assessment.all_assessments
            if "temperature" in ass_dict:
                status_temp = ass_dict["temperature"].status.value
            if "humidity" in ass_dict:
                status_hum = ass_dict["humidity"].status.value
            if "dust" in ass_dict:
                status_dust = ass_dict["dust"].status.value
            if "noise" in ass_dict:
                status_noise = ass_dict["noise"].status.value
            if "gas" in ass_dict:
                status_gas = ass_dict["gas"].status.value

        snap_entry: Dict[str, Any] = {
            "Timestamp": time_only_str,
            "Full_Timestamp": now_str,
            "ISO_Timestamp": now_dt.isoformat(),
            "Tick": tick,
            "Mode": mode,
            "temperature": extracted_vals["temperature"],
            "humidity": extracted_vals["humidity"],
            "dust": extracted_vals["dust"],
            "noise": extracted_vals["noise"],
            "gas": extracted_vals["gas"],
            "status_temperature": status_temp,
            "status_humidity": status_hum,
            "status_dust": status_dust,
            "status_noise": status_noise,
            "status_gas": status_gas,
            "overall_status": overall_status_val,
            "overall_status_color": overall_status_color,
        }

        self.snapshots.append(snap_entry)

        # Enforce rolling buffer capacity
        if len(self.snapshots) > self.max_snapshots:
            self.snapshots.pop(0)

        return True

    def record_events_from_assessment(
        self,
        site_assessment: SiteHazardAssessment,
        tick: int = 0,
        timestamp: Optional[datetime] = None,
    ) -> List[HazardEvent]:
        """
        Evaluates active hazards and logs state transitions (both escalations and recoveries):
        - GREEN to ORANGE
        - ORANGE to RED
        - GREEN directly to RED
        - RED to ORANGE or GREEN
        - ORANGE to GREEN

        Strictly prevents logging duplicate events on static UI refreshes.
        """
        now_dt = timestamp or datetime.now()
        now_str = now_dt.strftime("%H:%M:%S")
        iso_str = now_dt.isoformat()
        newly_logged: List[HazardEvent] = []

        # We evaluate all assessments present
        assessments = site_assessment.all_assessments

        for key, assessment in assessments.items():
            current_status = assessment.status
            prev_status = self._last_param_status.get(key, HazardStatus.SAFE)

            # Check if there is a meaningful state transition
            if current_status != prev_status:
                threshold_info = getattr(assessment, "threshold_exceeded", None)
                if not threshold_info:
                    threshold_info = f"Threshold for {assessment.display_name} crossed"
                else:
                    threshold_info = str(threshold_info)

                if current_status == HazardStatus.SAFE:
                    rec_action = "Hazard resolved. Parameter returned to safe baseline. Continue standard site vigilance."
                    reason_msg = f"{assessment.display_name} recovered to safe baseline ({assessment.value:.1f} {assessment.unit})."
                else:
                    rec_action = assessment.recommended_actions[0] if assessment.recommended_actions else "Follow standard site precautions."
                    reason_msg = assessment.reason

                event = HazardEvent(
                    timestamp=now_str,
                    iso_timestamp=iso_str,
                    parameter_key=key,
                    display_name=assessment.display_name,
                    previous_status=prev_status,
                    new_status=current_status,
                    value=float(assessment.value),
                    unit=assessment.unit,
                    relevant_threshold=threshold_info,
                    reason=reason_msg,
                    recommended_action=rec_action,
                    tick=tick,
                )

                # Insert newest first for immediate UI feed access
                self.events.insert(0, event)
                newly_logged.append(event)
                self._last_param_status[key] = current_status

                # Trim events buffer if exceeded
                if len(self.events) > self.max_events:
                    self.events.pop()

        return newly_logged

    @property
    def chronological_events(self) -> List[HazardEvent]:
        """Returns events in ascending chronological order (oldest to newest)."""
        return list(reversed(self.events))

    def get_events(self, chronological: bool = False) -> List[HazardEvent]:
        """Returns events either newest-first (default) or ascending chronological order."""
        return list(reversed(self.events)) if chronological else list(self.events)

    def get_snapshots_dataframe(self) -> pd.DataFrame:
        """Returns the rolling snapshots as a pandas DataFrame."""
        if not self.snapshots:
            return pd.DataFrame(columns=[
                "Timestamp", "Tick", "Mode", "temperature", "humidity", "dust", "noise", "gas",
                "status_temperature", "status_humidity", "status_dust", "status_noise", "status_gas",
                "overall_status", "overall_status_color"
            ])
        return pd.DataFrame(self.snapshots)

    def get_events_dataframe(self, newest_first: bool = True) -> pd.DataFrame:
        """Returns recorded hazard events as a displayable pandas DataFrame."""
        if not self.events:
            return pd.DataFrame(columns=[
                "Timestamp", "Hazard Type", "State Transition", "Observed Value", "Severity",
                "Relevant Threshold", "Diagnosis", "Recommended Action"
            ])
        records = [e.to_dict() for e in self.events]
        if newest_first:
            records = list(reversed(records))
        return pd.DataFrame(records)

    def get_summary_statistics(self) -> Dict[str, Any]:
        """
        Calculates summary statistics across all recorded telemetry and events during the session.
        Calculates:
        - Min, Max, Average for all 5 parameters.
        - Number of warning events, critical events, and recovery events.
        - Time range covered (start time, end time, elapsed duration).
        - Safe handling of empty datasets.
        """
        params_info = {
            "temperature": {"name": "Temperature", "unit": "°C"},
            "humidity": {"name": "Relative Humidity", "unit": "%"},
            "dust": {"name": "Dust Concentration", "unit": "µg/m³"},
            "noise": {"name": "Noise Level", "unit": "dB"},
            "gas": {"name": "Gas Concentration", "unit": "ppm"},
        }

        if not self.snapshots:
            return {
                "has_data": False,
                "total_snapshots": 0,
                "total_events": 0,
                "time_range": {
                    "start": self.session_start_str,
                    "end": self.session_start_str,
                    "duration_seconds": 0.0,
                    "duration_formatted": "00:00:00",
                },
                "parameters": {
                    k: {"min": 0.0, "max": 0.0, "mean": 0.0, "unit": v["unit"], "name": v["name"], "count": 0}
                    for k, v in params_info.items()
                },
                "events_summary": {
                    "warning_events": 0,
                    "critical_events": 0,
                    "recovery_events": 0,
                    "total_events": 0,
                },
                "disclaimer": SIMULATION_DISCLAIMER_TEXT,
            }

        df = pd.DataFrame(self.snapshots)

        param_stats: Dict[str, Any] = {}
        for k, v in params_info.items():
            if k in df.columns and len(df[k].dropna()) > 0:
                s = pd.to_numeric(df[k], errors="coerce").dropna()
                param_stats[k] = {
                    "name": v["name"],
                    "unit": v["unit"],
                    "min": round(float(s.min()), 2),
                    "max": round(float(s.max()), 2),
                    "mean": round(float(s.mean()), 2),
                    "count": int(len(s)),
                }
            else:
                param_stats[k] = {
                    "name": v["name"],
                    "unit": v["unit"],
                    "min": 0.0,
                    "max": 0.0,
                    "mean": 0.0,
                    "count": 0,
                }

        # Time range calculation
        start_ts = self.snapshots[0].get("Full_Timestamp", self.session_start_str)
        end_ts = self.snapshots[-1].get("Full_Timestamp", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))

        duration_sec = 0.0
        try:
            dt_start = datetime.strptime(start_ts, "%Y-%m-%d %H:%M:%S")
            dt_end = datetime.strptime(end_ts, "%Y-%m-%d %H:%M:%S")
            duration_sec = max(0.0, (dt_end - dt_start).total_seconds())
        except Exception:
            duration_sec = 0.0

        mins, secs = divmod(int(duration_sec), 60)
        hours, mins = divmod(mins, 60)
        duration_fmt = f"{hours:02d}:{mins:02d}:{secs:02d}"

        # Event counts
        warning_count = sum(1 for e in self.events if e.is_warning)
        critical_count = sum(1 for e in self.events if e.is_danger)
        recovery_count = sum(1 for e in self.events if e.is_recovery)

        return {
            "has_data": True,
            "total_snapshots": len(self.snapshots),
            "total_events": len(self.events),
            "time_range": {
                "start": start_ts,
                "end": end_ts,
                "duration_seconds": round(duration_sec, 1),
                "duration_formatted": duration_fmt,
            },
            "parameters": param_stats,
            "events_summary": {
                "warning_events": warning_count,
                "critical_events": critical_count,
                "recovery_events": recovery_count,
                "total_events": len(self.events),
            },
            "disclaimer": SIMULATION_DISCLAIMER_TEXT,
        }

    def export_readings_csv(self) -> str:
        """
        Exports historical readings as a standardized CSV string.
        Includes units in column headers and handles empty datasets gracefully.
        """
        export_columns = {
            "Full_Timestamp": "Timestamp",
            "temperature": "Temperature (deg C)",
            "humidity": "Relative Humidity (%)",
            "dust": "Dust Concentration (ug/m3)",
            "noise": "Noise Level (dB)",
            "gas": "Gas Concentration (ppm)",
            "status_temperature": "Status Temperature",
            "status_humidity": "Status Humidity",
            "status_dust": "Status Dust",
            "status_noise": "Status Noise",
            "status_gas": "Status Gas",
            "overall_status": "Overall Site Status",
            "Mode": "Simulation Mode",
            "Tick": "Simulation Tick",
        }

        if not self.snapshots:
            empty_df = pd.DataFrame(columns=list(export_columns.values()))
            header_comment = f"# SafeEdge Environmental Hazard Monitor — Historical Telemetry Log\n# {SIMULATION_DISCLAIMER_TEXT}\n"
            return header_comment + empty_df.to_csv(index=False)

        df = pd.DataFrame(self.snapshots)
        available_cols = [c for c in export_columns.keys() if c in df.columns]
        df_export = df[available_cols].rename(columns={c: export_columns[c] for c in available_cols})

        header_comment = f"# SafeEdge Environmental Hazard Monitor — Historical Telemetry Log\n# {SIMULATION_DISCLAIMER_TEXT}\n"
        return header_comment + df_export.to_csv(index=False)

    def export_events_csv(self) -> str:
        """
        Exports hazard state transition events as a standardized CSV string.
        """
        export_columns = [
            "Timestamp", "Hazard Name", "Parameter Key", "Previous Status", "New Status",
            "State Transition", "Observed Value", "Unit", "Relevant Threshold",
            "Diagnostic Reason", "Recommended Action", "Simulation Tick"
        ]

        if not self.events:
            empty_df = pd.DataFrame(columns=export_columns)
            header_comment = f"# SafeEdge Environmental Hazard Monitor — Hazard Event Log\n# {SIMULATION_DISCLAIMER_TEXT}\n"
            return header_comment + empty_df.to_csv(index=False)

        rows = []
        for e in self.chronological_events:
            rows.append({
                "Timestamp": e.timestamp,
                "Hazard Name": e.display_name,
                "Parameter Key": e.parameter_key,
                "Previous Status": e.previous_status.value,
                "New Status": e.new_status.value,
                "State Transition": f"{e.previous_status.value} -> {e.new_status.value}",
                "Observed Value": round(float(e.value), 2) if not (math.isnan(e.value) or math.isinf(e.value)) else 0.0,
                "Unit": e.unit,
                "Relevant Threshold": e.relevant_threshold,
                "Diagnostic Reason": e.reason,
                "Recommended Action": e.recommended_action,
                "Simulation Tick": e.tick,
            })

        df_export = pd.DataFrame(rows)
        header_comment = f"# SafeEdge Environmental Hazard Monitor — Hazard Event Log\n# {SIMULATION_DISCLAIMER_TEXT}\n"
        return header_comment + df_export.to_csv(index=False)

    def export_json_report(
        self,
        configured_thresholds: Optional[Dict[str, Any]] = None,
        additional_metadata: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """
        Exports a complete structured audit report as a Python dictionary.
        """
        now = datetime.now()
        stats = self.get_summary_statistics()

        report: Dict[str, Any] = {
            "report_metadata": {
                "generated_at": now.strftime("%Y-%m-%d %H:%M:%S"),
                "iso_timestamp": now.isoformat(),
                "project_name": "SafeEdge-PPE-Vision",
                "module_name": "SafeEdge Environmental Hazard Monitor",
                "phase": "Phase 4: Environmental Hazard History and Report Generation",
                "regulatory_disclaimer": SIMULATION_DISCLAIMER_TEXT,
                "session_start_time": self.session_start_str,
                "session_duration_seconds": stats["time_range"]["duration_seconds"],
                "session_duration_formatted": stats["time_range"]["duration_formatted"],
                "total_readings_recorded": len(self.snapshots),
                "total_hazard_events": len(self.events),
            },
            "data_limitations": {
                "storage_model": "In-memory session buffer (unpersisted across process termination)",
                "data_source": "Software simulated bounded random walk and operator manual controls",
                "sensor_integration": "None (Simulation mode only)",
                "certification_warning": "Not valid for statutory workplace compliance or regulatory reporting.",
            },
            "configured_thresholds": configured_thresholds or {},
            "summary_statistics": stats,
            "historical_readings": self.snapshots,
            "hazard_events": [e.to_export_dict() for e in self.chronological_events],
        }

        if additional_metadata:
            report["additional_metadata"] = additional_metadata

        return report

    def export_json_report_str(
        self,
        configured_thresholds: Optional[Dict[str, Any]] = None,
        additional_metadata: Optional[Dict[str, Any]] = None,
        indent: int = 2,
    ) -> str:
        """Returns the complete structured JSON report as a formatted string."""
        report_dict = self.export_json_report(configured_thresholds, additional_metadata)
        return json.dumps(report_dict, indent=indent, default=str)

    def clear(self) -> None:
        """Restores empty session history state."""
        self.snapshots.clear()
        self.events.clear()
        self._last_param_status.clear()
        self._last_snapshot_fingerprint = None
        self.session_start_time = datetime.now()
        self.session_start_str = self.session_start_time.strftime("%Y-%m-%d %H:%M:%S")
